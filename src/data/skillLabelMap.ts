function slugify(label: string): string {
  return label.toLowerCase().replace(/[^a-z0-9+#]/g, "");
}

/** Every vocab term a Skill Reviews label corresponds to, falling back to
 *  a normalized slug of the label itself if no explicit mapping exists. */
export function resolveSkillVocabTerms(label: string): string[] {
  return SKILL_LABEL_TO_VOCAB[label] ?? [slugify(label)];
}
